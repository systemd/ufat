//! Generates src/name/fold_table.rs, the case folding table of the `name`
//! module.
//!
//! The table lists every character whose `char::to_uppercase()` is a single
//! character other than itself, together with that character, as the
//! Unicode tables of the compiler running this program have them. Only a
//! compiler that ships the pinned Unicode version may generate it, so that
//! the table does not move with the compiler. rustc 1.85.0 ships 16.0.0:
//!
//!     RUSTC="rustup run 1.85.0 rustc" meson setup build-1.85
//!     meson compile -C build-1.85 update-fold-table
//!
//! Moving the table to a newer Unicode version changes which names ufat
//! tells apart, so it is a deliberate change: update `PINNED`, regenerate
//! with a compiler that ships that version and say so in the commit.

use std::io::{self, Write};
use std::process::exit;

/// The Unicode version the table is pinned to.
const PINNED: (u8, u8, u8) = (16, 0, 0);

/// Pairs per line of the generated table; four fit the 120 column width.
const PER_LINE: usize = 4;

fn main() {
    let (major, minor, update) = char::UNICODE_VERSION;
    if char::UNICODE_VERSION != PINNED {
        eprintln!(
            "fold-table: this compiler ships Unicode {}.{}.{} but the table is pinned to {}.{}.{}; \
             build the generator with a compiler that ships the pinned version, for example in a \
             build directory set up with `RUSTC=\"rustup run 1.85.0 rustc\" meson setup`",
            major, minor, update, PINNED.0, PINNED.1, PINNED.2
        );
        exit(1);
    }

    let mut pairs = Vec::new();
    for c in char::MIN..=char::MAX {
        let mut upper = c.to_uppercase();
        if let (Some(u), None) = (upper.next(), upper.next()) {
            if u != c {
                pairs.push((c, u));
            }
        }
    }

    let mut out = String::new();
    out.push_str("// SPDX-License-Identifier: LGPL-2.1-or-later\n");
    out.push_str("//! The case folding table of the `name` module, generated by\n");
    out.push_str("//! tools/fold-table.rs. Do not edit; `meson compile update-fold-table`\n");
    out.push_str("//! regenerates it and src/name.rs explains the rule.\n\n");
    out.push_str("/// The Unicode version the table was generated from.\n");
    out.push_str(&format!(
        "pub(super) const UNICODE_VERSION: (u8, u8, u8) = ({}, {}, {});\n\n",
        major, minor, update
    ));
    out.push_str(&format!(
        "/// Every character whose upper case form is a single other character,\n\
         /// with that form: {} pairs, sorted by character.\n",
        pairs.len()
    ));
    out.push_str("#[rustfmt::skip]\n");
    out.push_str("pub(super) static PAIRS: &[(char, char)] = &[\n");
    for chunk in pairs.chunks(PER_LINE) {
        let items: Vec<String> = chunk
            .iter()
            .map(|&(lower, upper)| format!("('\\u{{{:04x}}}', '\\u{{{:04x}}}'),", lower as u32, upper as u32))
            .collect();
        out.push_str(&format!("    {}\n", items.join(" ")));
    }
    out.push_str("];\n");

    if let Err(e) = io::stdout().write_all(out.as_bytes()) {
        eprintln!("fold-table: writing the table: {}", e);
        exit(1);
    }
}
