//! Generates src/name/fold_table.rs, the case folding table of the `name`
//! module, from UnicodeData.txt and SpecialCasing.txt of the Unicode
//! Character Database in the directory given:
//!
//!     cargo run --locked -q -p fold-table UCD_DIR > fold_table.rs
//!
//! The table lists every character whose upper case is a single other
//! character, together with that character. The upper case of a character
//! is its unconditional entry in SpecialCasing.txt, else the upper case
//! field of UnicodeData.txt, else the character itself. The table comes
//! from Unicode 16.0.0 and never changes, see HACKING.md.

use std::collections::BTreeMap;
use std::fs;
use std::io::{self, Write};
use std::path::Path;
use std::process::exit;

/// Pairs per line of the generated table; four fit the 120 column width.
const PER_LINE: usize = 4;

fn fail(message: &str) -> ! {
    eprintln!("fold-table: {}", message);
    exit(1);
}

/// A code point as the UCD files write it: hex digits.
fn code_point(text: &str, place: &str) -> char {
    u32::from_str_radix(text, 16)
        .ok()
        .and_then(char::from_u32)
        .unwrap_or_else(|| fail(&format!("{}: '{}' is not a code point", place, text)))
}

fn main() {
    let args: Vec<_> = std::env::args_os().skip(1).collect();
    let [dir] = args.as_slice() else {
        fail("usage: fold-table UCD_DIR, a directory with UnicodeData.txt and SpecialCasing.txt");
    };
    let read = |name: &str| {
        let path = Path::new(dir).join(name);
        fs::read_to_string(&path).unwrap_or_else(|e| fail(&format!("{}: {}", path.display(), e)))
    };
    let data = read("UnicodeData.txt");
    let special = read("SpecialCasing.txt");

    // The version is in the first line of SpecialCasing.txt, as in
    // "# SpecialCasing-16.0.0.txt".
    let version: Vec<u8> = special
        .lines()
        .next()
        .and_then(|l| l.strip_prefix("# SpecialCasing-"))
        .and_then(|l| l.strip_suffix(".txt"))
        .map(|v| v.split('.').filter_map(|n| n.parse().ok()).collect())
        .unwrap_or_default();
    let [major, minor, update] = version.as_slice() else {
        fail("SpecialCasing.txt does not start with its version");
    };

    // The upper case of every character that has one: field 12 of
    // UnicodeData.txt, replaced by the unconditional entries of
    // SpecialCasing.txt. The lines of a range carry no mappings.
    let mut upper: BTreeMap<char, Vec<char>> = BTreeMap::new();
    for (i, line) in data.lines().enumerate() {
        let place = format!("UnicodeData.txt:{}", i + 1);
        let fields: Vec<&str> = line.split(';').collect();
        if fields.len() != 15 {
            fail(&format!("{}: not 15 fields", place));
        }
        if !fields[12].is_empty() {
            upper.insert(code_point(fields[0], &place), vec![code_point(fields[12], &place)]);
        }
    }
    for (i, line) in special.lines().enumerate() {
        let place = format!("SpecialCasing.txt:{}", i + 1);
        let line = line.split('#').next().unwrap_or_default().trim();
        if line.is_empty() {
            continue;
        }
        // code; lower; title; upper; then the conditions, if any.
        let fields: Vec<&str> = line.split(';').map(str::trim).collect();
        match fields.as_slice() {
            [code, _, _, up, ""] => {
                let up = up.split_whitespace().map(|c| code_point(c, &place)).collect();
                upper.insert(code_point(code, &place), up);
            }
            [_, _, _, _, _, ""] => {}
            _ => fail(&format!("{}: not an entry", place)),
        }
    }

    let mut pairs = Vec::new();
    for (&c, up) in &upper {
        if let [u] = up[..] {
            if u != c {
                pairs.push((c, u));
            }
        }
    }
    // Folding is idempotent: no upper case form folds any further.
    for &(c, u) in &pairs {
        if let Some(&[v]) = upper.get(&u).map(Vec::as_slice) {
            if v != u {
                fail(&format!(
                    "U+{:04X} folds to U+{:04X}, which folds to U+{:04X}",
                    u32::from(c),
                    u32::from(u),
                    u32::from(v)
                ));
            }
        }
    }

    let mut out = String::new();
    out.push_str("// SPDX-License-Identifier: LGPL-2.1-or-later\n");
    out.push_str("//! The case folding table of the `name` module, generated by\n");
    out.push_str("//! tools/fold-table.rs from UnicodeData.txt and SpecialCasing.txt of\n");
    out.push_str(&format!(
        "//! Unicode {}.{}.{}. Do not edit; HACKING.md says how to check it, and\n",
        major, minor, update
    ));
    out.push_str("//! src/name.rs explains the rule.\n\n");
    out.push_str("/// The Unicode version the table was generated from.\n");
    out.push_str(&format!(
        "pub(super) const UNICODE_VERSION: (u8, u8, u8) = ({}, {}, {});\n\n",
        major, minor, update
    ));
    out.push_str(&format!(
        "/// Every character whose upper case form is a single other character,\n\
         /// with that form: {} pairs, sorted by character.\n",
        pairs.len()
    ));
    out.push_str("#[rustfmt::skip]\n");
    out.push_str("pub(super) static PAIRS: &[(char, char)] = &[\n");
    for chunk in pairs.chunks(PER_LINE) {
        let items: Vec<String> = chunk
            .iter()
            .map(|&(lower, upper)| format!("('\\u{{{:04x}}}', '\\u{{{:04x}}}'),", lower as u32, upper as u32))
            .collect();
        out.push_str(&format!("    {}\n", items.join(" ")));
    }
    out.push_str("];\n");

    if let Err(e) = io::stdout().write_all(out.as_bytes()) {
        fail(&format!("writing the table: {}", e));
    }
}
